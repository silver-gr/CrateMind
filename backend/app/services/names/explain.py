SILENT = {"D2"}  # printed only when no other step explains the change
SOURCE_TEXT = {"scanner": "την ανάγνωση του σαρωτή", "spotify": "το Spotify", "soundcloud": "το SoundCloud"}


def text_of(s: Step) -> str:
    """The Greek text of one step; a few rules say where their value came from."""
    if s.rule == "R0":
        src = SOURCE_TEXT.get(s.evidence, "άλλη πηγή")
        what = "το όνομα" if s.field == "artist" else "τον τίτλο"
        if not s.before:
            return f"Δείχνεται ό,τι γράφει το tag του αρχείου για {what}· η τωρινή εμφάνιση δεν έδειχνε τίποτα"
        return f"Δείχνεται ό,τι γράφει το tag του αρχείου για {what}· η τωρινή εμφάνιση έδειχνε «{s.before}» από {src}"
    if s.rule == "C3" and s.evidence == "publisher":
        return "Επιλέχθηκε η γραφή του ονόματος από τον εκδότη στο SoundCloud"
    return RULE_TEXT.get(s.rule, "")


def reason(trail: list[Step], status: str, open_code: str = "") -> str:
    out: list[str] = []
    for s in trail:
        if s.rule in SILENT:
            continue
        text = text_of(s)
        if text and text not in out:
            out.append(text)
    if not out and any(s.rule in SILENT for s in trail):
        out.append(RULE_TEXT["D2"])
    if open_code:
        out.append(OPEN_TEXT.get(open_code, ""))
    if status == "none":
        out.append(RULE_TEXT["none"])
    return " · ".join(x for x in out if x)
