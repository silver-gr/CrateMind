def _d2_text(before: str, after: str) -> str:
    """D2: what the tidy-up changed, from the two values."""
    if " ".join(before.split()) == " ".join(after.split()) or before.replace(" ", "") == after.replace(" ", ""):
        return "Διορθώθηκαν τα κενά"
    gone = Counter(before.replace(" ", "")) - Counter(after.replace(" ", ""))
    added = Counter(after.replace(" ", "")) - Counter(before.replace(" ", ""))
    if added and set(added) <= set(")]}") and not gone:
        return "Έκλεισε η παρένθεση που είχε μείνει ανοιχτή"
    if gone and set(gone) <= set("()[]{}"):
        return "Αφαιρέθηκαν άδειες παρενθέσεις ή μια παρένθεση που δεν άνοιγε"
    shown = "".join(sorted(gone.elements(), key=before.find))
    if gone and not any(c.isalnum() for c in gone):
        return f"Αφαιρέθηκαν σημεία στίξης ή σύμβολα που περίσσευαν («{shown}»)"
    return f"Αφαιρέθηκαν χαρακτήρες που περίσσευαν στην αρχή ή στο τέλος («{shown}»)"


