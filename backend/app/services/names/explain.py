SILENT = {"D2"}


def reason(trail: list[Step], status: str, open_code: str = "") -> str:
    out: list[str] = []
    for s in trail:
        if s.rule in SILENT:
            continue
        text = RULE_TEXT.get(s.rule)
        if text and text not in out:
            out.append(text)
    if open_code:
        out.append(OPEN_TEXT.get(open_code, ""))
    return " · ".join(x for x in out if x)
