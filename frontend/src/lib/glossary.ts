/** The entries for a build: without the Maximizer (every CI and release build), its entry, its «Δες επίσης» links and
 *  the «MAX» sentence are left out. */
export function glossaryFor(maximizer: boolean): readonly GlossaryTerm[] {
  if (maximizer) return GLOSSARY_ALL;
  return GLOSSARY_ALL.filter(t => t.id !== "maximizer").map(t => ({
    ...t,
    act: t.act.replace(MAX_SENTENCE, ""),
    see: t.see?.filter(id => id !== "maximizer"),
  }));
}

/** The terms whose name, other names or text contain every word of `query` (case- and accent-insensitive). */
export function filterGlossary(terms: readonly GlossaryTerm[], query: string): GlossaryTerm[] {
  const words = normalizeSearch(query).split(/\s+/).filter(Boolean);
  if (words.length === 0) return [...terms];
  return terms.filter(t => {
    const text = normalizeSearch(`${t.term} ${t.aka ?? ""} ${t.what} ${t.hear} ${t.act}`);
    return words.every(w => text.includes(w));
  });
}

